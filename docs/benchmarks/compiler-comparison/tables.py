"""Render results.json and scaling.json as the Markdown tables used in REPORT.md.

    python3 docs/benchmarks/compiler-comparison/tables.py > /tmp/tables.md
"""
from __future__ import annotations

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"legacy": "Python (legacy)", "zakc-main": "zakc @ main", "zakc": "zakc + line index"}


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(header))) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def number(value: float | None, digits: int = 1) -> str:
    if value is None:
        return "—"
    return f"{value:,.{digits}f}"


def ratio(numerator: float, denominator: float) -> str:
    return f"{numerator / denominator:.1f}×"


def net(entry: dict, event: str) -> float | None:
    """Counter for the measured rounds only: full run minus a zero-round run."""
    full, idle = entry["throughput"]["perf"].get(event), entry["startup_only_perf"].get(event)
    if full is None or idle is None:
        return None
    return full - idle


def main() -> None:
    results = json.loads((HERE / "results.json").read_text())
    environment = results["environment"]
    out = [f"<!-- generated by tables.py from results.json (git {environment['git']}) -->"]

    for kind, label in (("valid", "Valid programs"), ("invalid", "Invalid programs (error path)")):
        section = results[kind]
        legacy = section["legacy"]["throughput"]["us_per_program"]
        rows = []
        for name, entry in section.items():
            t, latency = entry["throughput"], entry["latency"]["latency_us"]
            rows.append([NAMES[name], number(t["us_per_program"]), number(t["programs_per_second"], 0),
                         number(latency["p50"]), number(latency["p90"]), number(latency["p99"]), number(latency["max"]),
                         ratio(legacy, t["us_per_program"])])
        out.append(f"\n**{label}: {section['legacy']['throughput']['programs']} programs**\n")
        out.append(table(["Implementation", "Mean µs/program", "Programs/s", "p50 µs", "p90 µs", "p99 µs", "max µs",
                          "Speed-up vs Python"], rows))

    out.append("\n**Native Rust (no Python, `examples/throughput`)**\n")
    rows = []
    for key, label in (("native_rust_throughput_main", "zakc @ main"), ("native_rust_throughput", "zakc + line index"),
                       ("native_rust_throughput_target_cpu_native", "zakc + line index, `-C target-cpu=native`")):
        if key in results:
            rows.append([label, number(results[key]["microseconds_per_program"]), f"{results[key]['compilations']:,}"])
    out.append(table(["Build", "µs/program", "Compilations"], rows))

    out.append("\n**CPU counters (perf stat, user space, measured rounds only, per compiled program)**\n")
    rows = []
    for kind in ("valid", "invalid"):
        for name, entry in results[kind].items():
            t = entry["throughput"]
            count = t["rounds"] * t["programs"]
            instructions, cycles = net(entry, "instructions"), net(entry, "cycles")
            cache_refs, cache_misses = net(entry, "cache-references"), net(entry, "cache-misses")
            branches, branch_misses = net(entry, "branches"), net(entry, "branch-misses")
            rows.append([kind, NAMES[name], number(instructions / count / 1e3, 0), number(cycles / count / 1e3, 0),
                         f"{instructions / cycles:.2f}", f"{100 * cache_misses / cache_refs:.1f}%",
                         f"{100 * branch_misses / branches:.2f}%", number(net(entry, "task-clock") / count * 1e3, 1)])
    out.append(table(["Corpus", "Implementation", "k instructions", "k cycles", "IPC", "Cache miss rate",
                      "Branch miss rate", "CPU µs (task-clock)"], rows))

    out.append("\n**Memory**\n")
    rows = []
    for kind in ("valid", "invalid"):
        for name, entry in results[kind].items():
            t, heap = entry["throughput"], entry["tracemalloc"]["python_heap_peak_bytes"]
            rows.append([kind, NAMES[name], number(t["rss_interpreter_kib"] / 1024), number(t["rss_after_import_kib"] / 1024),
                         number((t["rss_after_import_kib"] - t["rss_interpreter_kib"]) / 1024),
                         number(entry["gnu_time_peak_rss_kib"] / 1024), number(heap["median"] / 1024),
                         number(heap["max"] / 1024)])
    out.append(table(["Corpus", "Implementation", "RSS bare interpreter MiB", "RSS after import MiB", "Import cost MiB",
                      "Peak RSS MiB", "Python heap/compile median KiB", "Python heap/compile max KiB"], rows))

    out.append("\n**Cold start (process start + import, or CLI on one reference; median of 20)**\n")
    rows = []
    for name, entry in results["cold_start"].items():
        perf = entry["perf"]
        rows.append([f"`{name}`", number(entry["median_ms"], 2), number(perf.get("task-clock"), 2),
                     number((perf.get("instructions") or 0) / 1e6, 1), number(perf.get("page-faults"), 0)])
    out.append(table(["Command", "Wall ms", "CPU ms", "M instructions", "Page faults"], rows))

    scaling_path = HERE / "scaling.json"
    if scaling_path.exists():
        rows_by_shape: dict[str, dict[int, dict[str, dict]]] = {}
        for row in json.loads(scaling_path.read_text())["rows"]:
            rows_by_shape.setdefault(row["shape"], {}).setdefault(row["size"], {})[row["implementation"]] = row
        labels = {"width": "Width: concatenated task references (all 50, cycled)",
                  "width_branch_free": "Width: concatenated branch-free references (11 without `?`, cycled)",
                  "nesting": "Nesting: alternating loops and conditionals"}
        for shape, sizes in rows_by_shape.items():
            out.append(f"\n**{labels[shape]}**\n")
            rows = []
            for size, by_name in sorted(sizes.items()):
                size_bytes = next((r["bytes"] for r in by_name.values() if r.get("bytes")), None)
                cells = [str(size), number(size_bytes / 1024, 1) if size_bytes else "—"]
                for name in NAMES:
                    row = by_name.get(name, {})
                    if "median_ms" in row:
                        cells.append(number(row["median_ms"], 2))
                    elif row.get("skipped"):
                        cells.append("skipped")
                    else:
                        cells.append("rejected" if row else "—")
                for name in NAMES:
                    row = by_name.get(name, {})
                    cells.append(number(row["max_rss_kib"] / 1024, 0) if "max_rss_kib" in row else "—")
                rows.append(cells)
            header = ["Functions" if shape != "nesting" else "Depth", "KiB"]
            header += [f"{NAMES[n]} ms" for n in NAMES] + [f"{NAMES[n]} peak RSS MiB" for n in NAMES]
            out.append(table(header, rows))
            # Log-log slope between the two largest sizes each implementation completed.
            slopes = []
            for name in NAMES:
                points = [(r["bytes"], r["median_ms"]) for s in sorted(sizes) if "median_ms" in (r := sizes[s].get(name, {}))]
                points = [p for p in points if p[0] >= 2000] or points
                if len(points) >= 2:
                    (x0, y0), (x1, y1) = points[0], points[-1]
                    slopes.append(f"{NAMES[name]} ≈ n^{math.log(y1 / y0) / math.log(x1 / x0):.2f} "
                                  f"({number(x0 / 1024)}–{number(x1 / 1024)} KiB)")
            out.append("\nGrowth exponent (log-log slope, time vs bytes): " + "; ".join(slopes) + ".")
    print("\n".join(out))


if __name__ == "__main__":
    main()
